#!/bin/bash

check_disk_space() {
  # Принимает 1 аргумент — путь к файловой системе (например, /)
  # Проверяет, что аргумент передан
  # Проверяет, существует ли путь
  # Выводит процент использования диска для этой файловой системы
  # Возвращает 0 при успехе, 1 при ошибке 

  # Проверка аргумента
  if [ -z "$1" ]; then
    echo "Ошибка: нет аргумента"
    return 1
  fi
  
  # Проверка пути
  if [ ! -e "$1" ]; then
    echo "Ошибка: путь не существует"
    return 1
  fi
  
  # Получение процента использования
  df "$1" | awk 'NR==2 {print $5}'
  return 0
}

# Тесты
check_disk_space /      # Вывод: процент использования
check_disk_space /home  # Вывод: процент использования
check_disk_space        # Ошибка
